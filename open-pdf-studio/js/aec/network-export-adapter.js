// OpenCivil — Reviewed Network Export Adapter
// Direct graph-to-LandXML export path for reviewed/edited network graphs.
// Does NOT convert back to raw records — works directly from the graph model.
//
// Used when aecNetworkStore has a reviewed graph. Falls back to the standard
// record-based export when no reviewed graph is available.

import { getNetworkGraph, networkGraphAvailable } from '../solid/stores/aecNetworkStore.js';
import { recordsToLandXML, parseScaleFactor } from './civil3d-export.js';

// ============================================================
// Direct Graph → LandXML
// ============================================================

/**
 * Generate LandXML directly from the reviewed graph in aecNetworkStore.
 * This bypasses the record-based buildConfirmedNetwork pipeline and uses
 * the graph as-is (including any manual edits from the review UI).
 *
 * @param {Object} [options]
 * @returns {string|null}  LandXML string or null if no graph
 */
export function graphToLandXML(options = {}) {
  const graph = getNetworkGraph();
  if (!graph) return null;

  const {
    projectName = 'Open Civil Studio Export (Reviewed)',
    networkName = 'Storm Drain Network',
  } = options;

  const structures = graph.structureList || [];
  const pipes = graph.pipes || [];
  const unresolvedPipes = graph.unresolvedPipes || [];

  if (structures.length === 0 && pipes.length === 0) return null;

  const now = new Date();
  const dateStr = now.toISOString().slice(0, 10);
  const timeStr = now.toISOString().slice(11, 19);

  const lines = [];
  lines.push('<?xml version="1.0" encoding="UTF-8"?>');
  lines.push('<!-- Generated by Open Civil Studio / OpenCivil - LandXML Pipe Network Export (Reviewed) -->');
  lines.push(`<!-- Date: ${dateStr} ${timeStr} -->`);
  lines.push(`<!-- Structures: ${structures.length}, Pipes: ${pipes.length}, Unresolved: ${unresolvedPipes.length} -->`);
  lines.push('<LandXML xmlns="http://www.landxml.org/schema/LandXML-1.2"');
  lines.push('         xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"');
  lines.push('         xsi:schemaLocation="http://www.landxml.org/schema/LandXML-1.2 http://www.landxml.org/schema/LandXML-1.2/LandXML-1.2.xsd"');
  lines.push(`         version="1.2" date="${dateStr}" time="${timeStr}">`);

  lines.push('  <Units>');
  lines.push('    <Imperial linearUnit="foot" areaUnit="squareFoot" volumeUnit="cubicFoot"');
  lines.push('             temperatureUnit="fahrenheit" pressureUnit="inchHG"');
  lines.push('             diameterUnit="inch" flowUnit="cubicFeetSecond" />');
  lines.push('  </Units>');

  lines.push(`  <Project name="${_esc(projectName)}" />`);
  lines.push('  <Application name="Open Civil Studio" manufacturer="OpenCivil LLC"');
  lines.push('               version="0.1.0" manufacturerURL="https://oldo.ai" />');

  lines.push('  <PipeNetworks>');
  lines.push(`    <PipeNetwork name="${_esc(networkName)}" pipeNetType="Storm">`);

  // Structures — only those used by confirmed pipes
  const usedIds = new Set();
  for (const p of pipes) {
    if (p.startRef) usedIds.add(p.startRef);
    if (p.endRef) usedIds.add(p.endRef);
  }

  lines.push('      <Structs>');
  for (const s of structures) {
    if (!usedIds.has(s.id)) continue;
    lines.push(`        <Struct name="${_esc(s.id)}" desc="${_esc(s.desc || s.type || '')}">`);
    if (s.diameter) {
      lines.push(`          <CircStruct diameter="${_esc(s.diameter)}" unit="inch" />`);
    }
    const n = _num(s.northing);
    const e = _num(s.easting);
    lines.push(`          <Center>${n} ${e}</Center>`);
    lines.push('        </Struct>');
  }
  lines.push('      </Structs>');

  // Pipes
  lines.push('      <Pipes>');
  for (const p of pipes) {
    const attrs = [`name="${_esc(p.name)}"`];
    if (p.startRef) attrs.push(`startRef="${_esc(p.startRef)}"`);
    if (p.endRef) attrs.push(`endRef="${_esc(p.endRef)}"`);
    if (p.length > 0) attrs.push(`length="${_num(p.length, 2)}"`);
    if (p.slope > 0) attrs.push(`slope="${_num(p.slope, 6)}"`);

    lines.push(`        <Pipe ${attrs.join(' ')}>`);
    lines.push(`          <CircPipe diameter="${_esc(p.diameter)}" material="${_esc(p.material)}" unit="inch" />`);
    lines.push('        </Pipe>');
  }
  lines.push('      </Pipes>');

  // Unresolved pipe comments
  if (unresolvedPipes.length > 0) {
    lines.push('      <!-- Unresolved pipe runs omitted from export: -->');
    for (const u of unresolvedPipes) {
      const slopeStr = u.slope > 0 ? ` slope=${(u.slope * 100).toFixed(1)}%` : '';
      lines.push(`      <!-- ${u.name || 'Unresolved'} | ${u.length} LF | ${u.diameter}" ${u.material}${slopeStr} -->`);
      lines.push(`      <!--   ${u.warning || 'unresolved — requires manual assignment or multi-sheet context'} -->`);
    }
  }

  lines.push('    </PipeNetwork>');
  lines.push('  </PipeNetworks>');
  lines.push('</LandXML>');

  return lines.join('\n');
}

// ============================================================
// Download — Reviewed Graph Export
// ============================================================

/**
 * Download reviewed LandXML if a graph is available, otherwise fall back
 * to the standard record-based export.
 *
 * @param {Array} records  AEC records (for fallback)
 * @param {Object} [options]
 */
export function downloadReviewedCivil3d(records, options = {}) {
  let xml;

  if (networkGraphAvailable()) {
    // Reviewed graph export path
    xml = graphToLandXML(options);
    console.log('[network-export] Using reviewed graph export');
  } else {
    // Fallback to standard record-based export
    xml = recordsToLandXML(records, options);
    console.log('[network-export] Using standard record-based export (no reviewed graph)');
  }

  if (!xml) {
    alert('No pipe network data found. Extract AEC data first.');
    return;
  }

  const blob = new Blob([xml], { type: 'application/xml' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = options.filename || 'PipeNetwork_Reviewed.xml';
  a.click();
  URL.revokeObjectURL(url);
}

// ============================================================
// Helpers
// ============================================================

function _esc(str) {
  if (str == null) return '';
  return String(str)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&apos;');
}

function _num(val, decimals = 3) {
  const n = parseFloat(val);
  return isNaN(n) ? '0.000' : n.toFixed(decimals);
}
